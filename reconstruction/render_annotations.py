"""Render reviewed identifier changes without rewriting raw decompiler evidence.

The lexical pass never touches comments, strings, numeric literals or operators.
Every renamed block is hash-bound and must invert byte-for-byte to the raw input.
This proves preservation of the export, NOT correctness of its decompilation.
"""
import hashlib
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
TOKEN=re.compile(r'(?P<opaque>/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\')|(?P<identifier>\b[A-Za-z_]\w*\b)',re.S)
BLOCK=re.compile(r'/\* ===== (\S+) @ ([0-9a-fA-F]+) ===== \*/.*?(?=/\* =====|\Z)',re.S)


def digest(data): return hashlib.sha256(data).hexdigest()


def rename(text, mapping):
    if len(set(mapping.values()))!=len(mapping):raise ValueError('non-invertible naming map')
    identifiers={m.group('identifier') for m in TOKEN.finditer(text) if m.group('identifier')}
    for original,named in mapping.items():
        if not re.fullmatch(r'[A-Za-z_]\w*',named):raise ValueError('invalid C identifier')
        if named in identifiers and named!=original:raise ValueError('identifier collision: '+named)
    return TOKEN.sub(lambda m:mapping.get(m.group('identifier'),m.group(0)) if m.group('identifier') else m.group(0),text)


def render(raw, spec):
    if digest(raw.encode())!=spec['raw_source_sha256']:raise ValueError('raw export changed; review mappings')
    entries={e['address'][2:].lower():e for e in spec['functions']}
    globals=dict(spec['globals']);globals.update({e['original']:e['name'] for e in entries.values()})
    output=[];inventory=[];cursor=0;seen=set()
    for match in BLOCK.finditer(raw):
        output.append(rename(raw[cursor:match.start()],globals))
        address=match.group(2).lower();entry=entries.get(address);block=match.group(0)
        mapping=dict(globals)
        if entry:
            if digest(block.encode())!=entry['raw_block_sha256']:raise ValueError('reviewed block changed: '+address)
            ids={m.group('identifier') for m in TOKEN.finditer(block) if m.group('identifier')}
            if not set(entry['locals'])<=ids:raise ValueError('reviewed local missing: '+address)
            mapping.update(entry['locals']);seen.add(address)
        named=rename(block,mapping)
        if rename(named,{v:k for k,v in mapping.items()})!=block:raise ValueError('non-reversible rename: '+address)
        if entry:
            comment='\n/* REVIEWED ANNOTATION\n * Original: '+entry['original']+' @ 0x'+address+'\n * Evidence: '+entry['confidence']+'\n * '+entry['summary']+'\n * '+entry['notes']+'\n */\n'
            if '*/' in entry['summary']+entry['notes']:raise ValueError('unsafe comment')
            output.append(comment)
        output.append(named)
        inventory.append({'address':'0x'+address,'original':match.group(1),'readable_name':entry['name'] if entry else match.group(1),
                          'status':'reviewed' if entry else 'unresolved','warning_count':block.count('WARNING:'),
                          'local_names':entry['locals'] if entry else {}})
        cursor=match.end()
    if seen!=set(entries):raise ValueError('reviewed entry missing from export')
    output.append(rename(raw[cursor:],globals))
    return ''.join(output),inventory


def main():
    spec=json.loads((ROOT/'reconstruction/annotations/rc102.json').read_text())
    folder=ROOT/'firmware'/spec['target'];raw=(folder/'decompiled.c').read_text()
    if digest((folder/'flash.bin').read_bytes())!=spec['image_sha256']:raise ValueError('image changed')
    named,inventory=render(raw,spec)
    out=ROOT/'reconstruction/annotated';out.mkdir(exist_ok=True)
    header='/* Readable reference export. Generated by reconstruction/render_annotations.py.\n * Names are reviewed only where marked; remaining generic names are unresolved.\n * Operators/types/control flow and original warnings are preserved, including\n * known decompiler defects. This file is NOT a complete compilable firmware.\n */\n'
    readable=header+named
    (out/'rc102.c').write_text(readable)
    source_lines={m.group(2).lower():readable.count('\n',0,m.start())+1 for m in BLOCK.finditer(readable)}
    for row in inventory:row['annotated_line']=source_lines[row['address'][2:]]
    guide=['# Readable reference firmware','',
           'Generated companion to the raw rc-102 4.14 export. Original operators, types,',
           'control flow, strings and decompiler warnings remain unchanged. Reviewed names',
           'are descriptive; the other functions remain explicitly unresolved in `index.json`.','',
           'For compilable implementations, see [leaf routines](../rc102_leaf.c) and',
           '[floating-point predicate](../calibration.c). This export is not a source build.','',
           '| Address | Named function | Observed behavior |','| --- | --- | --- |']
    by_address={row['address']:row for row in inventory}
    for entry in spec['functions']:
        line=by_address[entry['address']]['annotated_line']
        guide.append('| `'+entry['address']+'` | ['+entry['name']+'](rc102.c#L'+str(line)+') | '+entry['summary']+' |')
    (out/'README.md').write_text('\n'.join(guide)+'\n')
    # Repository-wide review inventory: never transfer names between model builds
    # merely because an address or short instruction prefix happens to match.
    targets=[]
    for source in sorted((ROOT/'firmware').glob('*/*/decompiled.c')):
        text=source.read_text();target=str(source.parent.relative_to(ROOT/'firmware'))
        targets.append({'target':target,'raw_source_sha256':digest(source.read_bytes()),
                        'functions':len(list(BLOCK.finditer(text))),
                        'warning_occurrences':text.count('WARNING:'),
                        'reviewed_function_names':len(spec['functions']) if target==spec['target'] else 0})
    (out/'targets.json').write_text(json.dumps(targets,indent=2)+'\n')
    report={'target':spec['target'],'image_sha256':spec['image_sha256'],'raw_source_sha256':spec['raw_source_sha256'],
            'mapping_sha256':digest((ROOT/'reconstruction/annotations/rc102.json').read_bytes()),
            'output_sha256':digest((header+named).encode()),'total_functions':len(inventory),
            'reviewed_functions':sum(x['status']=='reviewed' for x in inventory),
            'renamed_locals':sum(len(x['local_names']) for x in inventory),'reversible_identifier_check':'PASS','functions':inventory}
    (out/'index.json').write_text(json.dumps(report,indent=2)+'\n')
    print(report['reviewed_functions'],'reviewed functions;',report['renamed_locals'],'meaningful local names;',len(inventory),'inventoried')
if __name__=='__main__':main()
